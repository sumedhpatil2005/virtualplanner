"""
Generate docs/urbanos/DATA_SOURCE_CATALOGUE.md from the dataset registry (never hand-edited).

    python -m datasets.catalogue_doc [--out PATH] [--check]

Every source and dataset in the registry: publisher, URL, licence (verbatim as recorded, else UNKNOWN), access method,
acquired?, active version / dates, CRS, coverage, size, sha256 (short), data class, suitability, features using it,
blocked reasons, latest update-monitor verdict, and pointers to the narrative catalogues that mention the dataset or its
source id (PUNE_DATA_AVAILABILITY.md, catalogue/*.md, MISSING_DATA_AND_COLLECTION_PLAN.md). Values come only from the
registry; an empty field prints UNKNOWN. `--check` exits 1 when the file on disk differs from what would be generated
from the same database.
"""
from __future__ import annotations

import argparse
import os
import re
import sys

from sqlalchemy import select
from sqlalchemy.orm import Session

from .models import DsDatasetEntity, DsFeatureDependencyEntity, DsFeatureEntity, DsSourceEntity
from .registry import (_j, dataset_status, evaluate_dependency, update_status, versions_of)
from .vocab import PUNE_BBOX, THEMES

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
DOCS = os.path.join(REPO, "docs", "urbanos")
OUT = os.path.join(DOCS, "DATA_SOURCE_CATALOGUE.md")
POINTER_DOCS = ["PUNE_DATA_AVAILABILITY.md", "catalogue/global.md", "catalogue/india.md", "catalogue/dsi.md",
                "MISSING_DATA_AND_COLLECTION_PLAN.md", "DEM_V3_ACTIVATION_RECOMMENDATION.md"]
U = "UNKNOWN"


def _v(x) -> str:
    if x is None:
        return U
    s = str(x).strip()
    return s if s else U


def _cell(x, limit: int | None = None) -> str:
    s = _v(x).replace("\n", " ").replace("|", "\\|")
    return s if limit is None or len(s) <= limit else s[: limit - 1] + "…"


def _size(n) -> str:
    if not n:
        return U
    n = float(n)
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024
    return U


def _coverage(bbox) -> str:
    if not (isinstance(bbox, list) and len(bbox) == 4):
        return U
    try:
        x0, y0, x1, y1 = (float(v) for v in bbox)
    except (TypeError, ValueError):
        return U
    px0, py0, px1, py1 = PUNE_BBOX
    ix, iy = max(0.0, min(x1, px1) - max(x0, px0)), max(0.0, min(y1, py1) - max(y0, py0))
    frac = ix * iy / ((px1 - px0) * (py1 - py0))
    return f"[{x0:.4g}, {y0:.4g}, {x1:.4g}, {y1:.4g}] (WGS84 bbox; {frac * 100:.0f} % of the Pune study box)"


def _pointers(ids: list[str]) -> list[str]:
    out = []
    for rel in POINTER_DOCS:
        p = os.path.join(DOCS, rel)
        try:
            with open(p, encoding="utf-8") as f:
                text = f.read()
        except OSError:
            continue
        for i in ids:
            if i and re.search(r"(?<![A-Za-z0-9_])" + re.escape(i) + r"(?![A-Za-z0-9_])", text):
                out.append(rel)
                break
    return out


def _features(db: Session) -> tuple[dict, dict]:
    feats = {f.id: f for f in db.scalars(select(DsFeatureEntity))}
    deps = list(db.scalars(select(DsFeatureDependencyEntity)))
    return feats, {d.id: d for d in deps}


def build(db: Session) -> str:
    feats, deps = _features(db)
    dep_eval = {d.id: evaluate_dependency(db, d) for d in deps.values()}
    sources = {s.id: s for s in db.scalars(select(DsSourceEntity).order_by(DsSourceEntity.id))}
    datasets = list(db.scalars(select(DsDatasetEntity).order_by(DsDatasetEntity.theme, DsDatasetEntity.id)))
    by_source: dict[str, list[str]] = {}
    for d in datasets:
        by_source.setdefault(d.source_id or "", []).append(d.id)

    counts: dict[str, int] = {}
    upd: dict[str, int] = {}
    rows = []
    for d in datasets:
        st = dataset_status(db, d)
        counts[st["status"]] = counts.get(st["status"], 0) + 1
        us = update_status(db, d.id)
        if us:
            upd[us["result"]] = upd.get(us["result"], 0) + 1
        rows.append((d, st, us))

    L: list[str] = []
    L.append("# UrbanOS data source catalogue (generated from the dataset registry)")
    L.append("")
    L.append("> Generated by `python -m datasets.catalogue_doc` from the registry tables (`ds_*`). **Do not edit by hand** — "
             "edit the manifests / processing.json / seeds / `classification_overrides.json` / `update_targets.json` and "
             "regenerate. Values are exactly as registered; an empty value prints **UNKNOWN**. Narrative research per source "
             "lives in the pointer documents named on each entry (PUNE_DATA_AVAILABILITY.md, catalogue/global.md, "
             "catalogue/india.md, catalogue/dsi.md); the plan for missing data is MISSING_DATA_AND_COLLECTION_PLAN.md.")
    L.append("")
    import datetime as _dt
    from database.connection import DATABASE_URL
    now = _dt.datetime.now(_dt.timezone(_dt.timedelta(hours=5, minutes=30))).isoformat(timespec="minutes")
    L.append(f"_Snapshot: registry database `{os.path.basename(DATABASE_URL.split('///')[-1])}`, generated {now} (IST)._")
    L.append("")
    L.append("Vocabulary: data class observed | inferred | estimated | derived | synthetic; suitability visualisation | "
             "screening | engineering (engineering only with a stated accuracy and an official source — none qualifies today). "
             "Status: available (active version) | pending_review (versions registered, none active) | not_acquired | synthetic. "
             "Update status = latest `python -m datasets.update_monitor` verdict across the probed URLs (never a download).")
    L.append("")
    L.append(f"**Totals:** {len(sources)} sources, {len(datasets)} datasets — "
             + ", ".join(f"{k} {v}" for k, v in sorted(counts.items()))
             + (". Update checks: " + ", ".join(f"{k} {v}" for k, v in sorted(upd.items())) if upd else ". Update checks: none recorded")
             + ".")
    L.append("")
    L.append("## 1. Sources")
    L.append("")
    L.append("| Source id | Publisher | URL | Access | Official | Registration | Licence (as recorded) | Datasets |")
    L.append("|---|---|---|---|---|---|---|---|")
    for s in sources.values():
        L.append(f"| `{s.id}` | {_cell(s.publisher)} | {_cell(s.url)} | {_cell(s.access_method)} | {'yes' if s.official else 'no'} | "
                 f"{'required' if s.registration_required else 'no'} | {_cell(s.licence_text)} | {len(by_source.get(s.id, []))} |")
    orphan = by_source.get("", [])
    if orphan:
        L.append("")
        L.append(f"Datasets with no source recorded ({len(orphan)}): " + ", ".join(f"`{x}`" for x in orphan)
                 + " — mostly catalogue mirrors and gap placeholders; derived datasets without a source inherit lineage via their inputs.")
    L.append("")
    L.append("## 2. Datasets by theme")
    theme = None
    for d, st, us in rows:
        if d.theme != theme:
            theme = d.theme
            L.append("")
            L.append(f"### {THEMES.get(theme, theme)} (`{theme}`)")
        vs = versions_of(db, d.id)
        act = next((v for v in reversed(vs) if v.review_status == "active"), None)
        pend = [v for v in vs if v.review_status == "pending_review"]
        src = sources.get(d.source_id) if d.source_id else None
        lic = act.licence_text if act and act.licence_text and act.licence_text != U else (src.licence_text if src else None)
        lic_url = (act.licence_url if act and act.licence_url else (src.licence_url if src else "")) or ""
        users, blocked = [], []
        for dep in deps.values():
            if dep.dataset_id == d.id or (dep.dataset_id is None and dep.theme == d.theme):
                f = feats.get(dep.feature_id)
                if f is None:
                    continue
                ev = dep_eval[dep.id]
                wired = " (wired)" if f.wired else (" (not wired)" if f.wired is False else "")
                users.append(f"`{f.id}`{wired}")
                if ev["state"] != "satisfied" and ev.get("dataset_id") in (d.id, None):
                    blocked.append(f"`{f.id}` needs {dep.required_quality}{'' if dep.required else ' (optional)'}: {ev['reason']}")
        L.append("")
        L.append(f"#### `{d.id}` — {d.title}")
        L.append("")
        L.append(f"- **Status:** {st['status']}" + (f"; {len(pend)} version(s) pending review ({', '.join(v.version_label for v in pend)})" if pend else "")
                 + f"; {len(vs)} version(s) registered")
        L.append(f"- **Source / publisher:** {('`' + src.id + '` — ' + _v(src.publisher)) if src else U}")
        L.append(f"- **URL:** {_v(src.url if src else None)}")
        L.append(f"- **Access method:** {_v(src.access_method if src else None)}"
                 + (" (registration required)" if src and src.registration_required else ""))
        L.append(f"- **Licence (verbatim as recorded):** {_v(lic)}" + (f" — {lic_url}" if lic_url else ""))
        if act:
            L.append(f"- **Active version:** {act.version_label} · retrieved {_v(act.retrieved_at)} · source updated {_v(act.source_updated_date)} · "
                     f"observation {_v(act.observation_start)} → {_v(act.observation_end)}")
            L.append(f"- **CRS:** {_v(act.crs)} · **Resolution:** {_v(act.resolution)} · **Format:** {_v(act.format)}")
            L.append(f"- **Coverage:** {_coverage(_j(act.coverage_bbox_json))}")
            L.append(f"- **Size:** {_size(act.size_bytes)} · **sha256:** {(act.sha256[:12] + '…') if act.sha256 else U}")
            L.append(f"- **Data class:** {_v(act.data_class)} · **Suitability:** {_v(act.suitability)}"
                     + (f" · **Accuracy:** {_cell(act.accuracy_statement, 200)}" if act.accuracy_statement else ""))
            pc = [p for p in pend if p.data_class and p.data_class != act.data_class]
            if pc:
                L.append(f"- **Pending reclassification:** " + "; ".join(f"{p.version_label} → {p.data_class}" for p in pc)
                         + " (registered as a new version; becomes effective only when a reviewer activates it)")
        else:
            L.append("- **Acquired:** no active version" + (" (registered versions await review)" if pend else " — not acquired"))
        if d.limitations:
            L.append(f"- **Limitations:** {_cell(d.limitations, 400)}")
        recs = _j(d.recommended_sources_json, []) or []
        if recs and not act:
            L.append("- **Recommended sources (metadata only):** " + "; ".join(
                f"{_v(r.get('name'))} ({_v(r.get('publisher'))}, licence {_v(r.get('licence'))})" for r in recs if isinstance(r, dict)))
        L.append(f"- **Features using it:** {', '.join(sorted(set(users))) if users else 'none recorded'}")
        if blocked:
            L.append("- **Blocked / limited:** " + " · ".join(sorted(set(blocked))))
        if us:
            when = (us['checked_at'] or '')[:16].replace('T', ' ')
            L.append(f"- **Update status:** {us['result']} ({us['urls_checked']} URL(s) probed; latest check {when or U} UTC) — {_cell(us['detail'], 300)}")
        else:
            L.append("- **Update status:** never checked")
        ptr = _pointers([d.id] + ([d.source_id] if d.source_id else []))
        if ptr:
            L.append("- **See also:** " + ", ".join(f"[{p}]({p})" for p in ptr))
    L.append("")
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true", help="exit 1 if the file differs from a fresh generation")
    a = ap.parse_args(argv)
    import main as app_main  # noqa: F401  (creates tables, seeds)
    from database.connection import SessionLocal
    with SessionLocal() as db:
        text = build(db)
        db.rollback()
    if a.check:
        try:
            with open(a.out, encoding="utf-8") as f:
                strip = lambda t: "\n".join(x for x in t.splitlines() if not x.startswith("_Snapshot:"))  # noqa: E731
                return 0 if strip(f.read()) == strip(text) else 1
        except OSError:
            return 1
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {a.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
